
# this file contains the functions simu that generates a simulated dataset

# INPUT
#' @param n: vector of the length of each sequence (default value: rep(100,1) for 1 sequence of length 100)
#' @param eta: parameter of the initial and transition densities
#' @param eta: parameter of the emission desntities
#' @param alpha: fixed for the initial density
#' @param seed: R seed (optional)
#' @param alpha: fixed parameter 

# OUTPUT
#' @return a list of 
  # x: list of same length as n. Each slot contains a latent random walks of length according to n
  # z: list of same length as n. Each slot contains an observed sequence generated by related x
  # star: true parameter composed of eta, epsilon and fixed alpha
  # seed: the R seed if provided as input

simu = function(n = rep(100, 1), eta, epsilon, alpha, seed = NA) {
  if(!is.na(seed)) {set.seed(seed)}
  x = z = list(rep(NA, length(n)))
  for (j in 1:length(n)) {
    xj = rep(NA, n[j])
    xj[1] = rnorm(1, alpha, epsilon)
    for (i in 2:n[j]) {xj[i] = xj[i-1] + rnorm(1, 0, epsilon)}
    z[[j]] = xj + rnorm(n[j], 0, eta)
    x[[j]] = xj # include xj in the list
  }
  res = list(x = x, z = z, star = c(eta = eta, epsilon = epsilon, alpha = alpha))
  return(res)
}

